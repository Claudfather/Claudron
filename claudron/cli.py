# ── output contract (docs/CLI_CONTRACT.md) ────────────────────────────
#
# stdout carries payload only (session hooks inject it verbatim);
# diagnostics go to stderr. --json emits exactly one envelope on stdout.


def _envelope(command: str, data: dict, findings: list[Finding] | None = None) -> dict:
    errors = [f.to_dict() for f in findings or [] if f.severity == "error"]
    warnings = [f.to_dict() for f in findings or [] if f.severity == "warning"]
    return {
        "ok": not errors,
        "command": command,
        "data": data,
        "warnings": warnings,
        "errors": errors,
    }


def _emit_json(command: str, data: dict, findings: list[Finding] | None = None) -> None:
    print(json.dumps(_envelope(command, data, findings), indent=2, default=str))


# ── vault resolution ──────────────────────────────────────────────────


def _resolve_vault(args) -> Vault:
    """Resolve vault from --vault flag, CLAUDRON_VAULT env, or walk-up."""
    vault_hint = getattr(args, "vault", None)
    if vault_hint:
        vault = detect(Path(vault_hint))
    elif os.environ.get("CLAUDRON_VAULT"):
        vault = detect(Path(os.environ["CLAUDRON_VAULT"]))
    else:
        vault = detect()

    if vault is None:
        print(
            "no vault found\n"
            "  create one:  claudron init <path>\n"
            "  or specify:  claudron --vault <path> <command>",
            file=sys.stderr,
        )
        sys.exit(3)  # environment error (docs/CLI_CONTRACT.md; was 2 pre-0.2.0)
    return vault


# ── .claudron config ─────────────────────────────────────────────────


def _detect_claudlobby_root(hint: Path | None = None) -> Path | None:
    """Walk up from *hint* (or CWD) looking for a claudlobby repo root.

    Marker: directory containing both ``library/`` and ``lib/``.
    """
    start = (hint or Path.cwd()).resolve()
    for candidate in [start, *start.parents]:
        if (candidate / "library").is_dir() and (candidate / "lib").is_dir():
            return candidate
    return None


def _require_claudlobby_root(args, command: str) -> Path:
    """Resolve claudlobby root or exit with a clear error."""
    cl_root = _detect_claudlobby_root(_claudlobby_hint(args))
    if cl_root is None:
        print(
            f"could not find claudlobby root\n"
            f"  {command} requires a claudlobby installation\n"
            f"  specify with: claudron {command} --claudlobby <path>",
            file=sys.stderr,
        )
        sys.exit(3)  # environment error (docs/CLI_CONTRACT.md; was 2 pre-0.2.0)
    return cl_root


def _read_claudron_config(path: Path) -> dict[str, str]:
    """Read shell-sourceable ``.claudron`` config file. Returns parsed key=value pairs."""
    result: dict[str, str] = {}
    if not path.is_file():
        return result
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            key, _, val = line.partition("=")
            result[key.strip()] = val.strip()
    return result


def _write_claudron_config(path: Path, vault_path: Path) -> None:
    """Write ``.claudron`` config pointing to vault."""
    path.write_text(
        f"# .claudron — auto-generated by claudron plug\nvault={vault_path}\n"
    )


