def cmd_hooks_install(args) -> int:
    snippet = settings_snippet(resolve_executable())
    if not args.write:
        print(json.dumps(snippet, indent=2))
        print(
            "\nmerge into ~/.claude/settings.json (or rerun with --write)",
            file=sys.stderr,
        )
        return 0

    settings_path = Path(
        args.settings or Path.home() / ".claude" / "settings.json"
    ).expanduser()
    current: dict = {}
    if settings_path.is_file():
        try:
            current = json.loads(settings_path.read_text())
        except json.JSONDecodeError:
            print(f"cannot parse {settings_path} — not touching it", file=sys.stderr)
            return 3
    merged = merge_settings(current, snippet)
    if merged == current:
        print("hooks already installed — no changes", file=sys.stderr)
        return 0
    print(f"writing {settings_path}", file=sys.stderr)
    settings_path.parent.mkdir(parents=True, exist_ok=True)
    settings_path.write_text(json.dumps(merged, indent=2) + "\n")
    return 0


def cmd_validate(args) -> int:
    strict = args.strict
    fix = args.fix
    vault = None
    if args.path:
        target = Path(args.path).expanduser().resolve()
        if not target.exists():
            print(f"no such path: {target}", file=sys.stderr)
            return 2
        # Vault context (for relative paths + shared-root rules) when the
        # target sits inside one; otherwise the target anchors itself.
        # Note: an explicit PATH anchors to its own vault — --vault is
        # deliberately not consulted here.
        probe = target if target.is_dir() else target.parent
        anchor = detect(probe)
        findings = validate_path(
            target, strict=strict, vault_root=anchor.root if anchor else probe
        )
        # The structure lens is whole-vault, so only when the target IS a
        # vault root — never for a single note or an inner subtree.
        if anchor and target == anchor.root:
            vault = anchor
    else:
        vault = _resolve_vault(args)
        findings = validate_path(vault.root, strict=strict, vault_root=vault.root)

    findings = list(findings)
    if vault is not None:
        structure = check_structure(vault, strict=strict)
        if fix:
            try:
                actions = fix_structure(vault, structure)
            except StructureError as e:
                print(f"--fix aborted: {e}", file=sys.stderr)
                return 1
            for action in actions:
                print(action, file=sys.stderr)
            structure = check_structure(vault, strict=strict)  # reflect repairs
        findings += structure
    elif fix:
        print(
            "--fix needs a whole vault — omit PATH or pass the vault root",
            file=sys.stderr,
        )
        return 2

    errors = [f for f in findings if f.severity == "error"]
    warnings = [f for f in findings if f.severity == "warning"]

    if args.json:
        _emit_json(
            "validate",
            {"errors": len(errors), "warnings": len(warnings), "strict": strict},
            findings,
        )
        return 1 if errors else 0

    for f in findings:
        loc = f.path + (f":{f.line}" if f.line else "")
        print(f"[{f.code}] {f.severity} {loc} — {f.message}")
    print(
        f"{len(errors)} error(s), {len(warnings)} warning(s)"
        + (" [strict]" if strict else ""),
        file=sys.stderr,
    )
    # No silent switch: name the --fix escape hatch when repairs are available.
    if not fix:
        fixable = [f for f in findings if is_fixable(f)]
        if fixable:
            print(
                f"→ {len(fixable)} fixable — run: claudron validate --fix",
                file=sys.stderr,
            )
    return 1 if errors else 0


