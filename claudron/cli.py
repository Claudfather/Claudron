def cmd_init(args) -> int:
    path = Path(args.path).expanduser()
    try:
        root = init(path, adopt=args.adopt)
    except VaultError as e:
        print(str(e), file=sys.stderr)
        return 2
    if args.json:
        _emit_json(
            "init",
            {"root": str(root), "scaffold": [f"_shared/{n}" for n in SCAFFOLD_TREE]},
        )
        return 0
    print(f"vault created at {root}")
    for name in SCAFFOLD_TREE:
        print(f"  _shared/{name}/")
    print("  projects/")
    return 0


def cmd_status(args) -> int:
    vault = _resolve_vault(args)
    info = status(vault, stale_days=getattr(args, "stale_days", 90))

    if args.json:
        _emit_json("status", info)
        return 0

    print(f"vault: {info['root']}")
    print(f"docs:  {info['total_docs']}  stale: {info['total_stale']}")
    if info["fleets"]:
        print(f"fleets: {', '.join(info['fleets'])}")
    if info["projects"]:
        print(f"projects: {', '.join(info['projects'])}")
    print()
    for tier_name, tier_info in info["tiers"].items():
        if tier_info["docs"] > 0 or args.verbose:
            stale_str = f"  ({tier_info['stale']} stale)" if tier_info["stale"] else ""
            print(f"  {tier_name}: {tier_info['docs']} docs{stale_str}")

    # Index state + vault warnings are diagnostics, not payload → stderr
    if not info["index_present"]:
        print("index: not built (will auto-build on first lookup)", file=sys.stderr)
    elif not info["index_fresh"]:
        print("index: stale (will auto-rebuild on next lookup)", file=sys.stderr)
    for w in info["warnings"]:
        print(f"warning: {w}", file=sys.stderr)
    return 0


def cmd_lookup(args) -> int:
    vault = _resolve_vault(args)
    query = " ".join(args.query)
    results = lookup(
        query,
        vault,
        project=args.project,
        fleet=args.fleet,
        limit=args.limit,
        include_archived=args.include_archived,
        include_expired=args.include_expired,
    )

    if not results:
        if args.json:
            _emit_json("lookup", {"query": query, "results": []})
        else:
            print(f"no results for '{query}'", file=sys.stderr)
        return 0

    if args.json:
        _emit_json(
            "lookup",
            {
                "query": query,
                "results": [
                    {
                        "title": r.doc.title,
                        "score": r.score,
                        "match_type": r.match_type,
                        "tier": r.doc.tier,
                        "path": str(r.doc.source_path.relative_to(vault.root)),
                        "tags": r.doc.tags,
                    }
                    for r in results
                ],
            },
        )
        return 0

    for r in results:
        rel = r.doc.source_path.relative_to(vault.root)
        tags = f"  [{', '.join(r.doc.tags)}]" if r.doc.tags else ""
        print(f"  [{r.score:3d}] {r.doc.title:<40s} {rel}{tags}")
    return 0


def cmd_index(args) -> int:
    vault = _resolve_vault(args)

    existing = None if args.full else load_index(vault)
    if existing is not None:
        count, rebuilt = len(existing.get("entries", [])), False
        msg = f"index up to date ({count} entries)"
    else:
        count, rebuilt = len(build_index(vault).get("entries", [])), True
        msg = f"indexed {count} docs"

    if args.json:
        _emit_json("index", {"entries": count, "rebuilt": rebuilt})
    else:
        print(msg, file=sys.stderr)
    return 0


