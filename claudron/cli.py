def cmd_init(args) -> int:
    path = Path(args.path).expanduser()
    try:
        root = init(path, adopt=args.adopt)
    except VaultError as e:
        print(str(e), file=sys.stderr)
        return 2

    if getattr(args, "personal", False):
        return _init_personal(args, root)

    if args.json:
        _emit_json(
            "init",
            {"root": str(root), "scaffold": [f"_shared/{n}" for n in SCAFFOLD_TREE]},
        )
        return 0
    print(f"vault created at {root}")
    for name in SCAFFOLD_TREE:
        print(f"  _shared/{name}/")
    print("  projects/")
    print("next: claudron validate   (audits the vault's structure)", file=sys.stderr)
    return 0


def _init_personal(args, root: Path) -> int:
    """The two-command bootstrap (E2): vault + git repo + a real first
    note proving the loop, then the machine-B one-liners. The smoke test
    is honest — a broken loop reports, it doesn't hide (verify mandate)."""
    from datetime import date

    # Git repo: init only when the vault isn't already inside one — never
    # re-init or commit over user history (--adopt case). run_git maps a
    # missing git binary to SyncError → clean exit 3 instead of a
    # traceback on the exact fresh machine this command targets.
    try:
        if run_git(root, "rev-parse", "--git-dir").returncode != 0:
            made = run_git(root, "init", "--initial-branch=main")
            if made.returncode != 0:
                print(
                    f"git init failed: {made.stderr.strip()[:200]}",
                    file=sys.stderr,
                )
                return 3
    except SyncError as exc:
        print(f"{exc} — the SD card needs git", file=sys.stderr)
        return 3  # environment error

    # Doctor-style smoke test as a REAL first note: capture through the
    # engine, then prove recall serves it. Bootstraps trust in the loop.
    vault = detect(root)
    try:
        result = capture(
            vault,
            note_type="knowledge",
            title="Vault Bootstrap",
            body=(
                f"Vault created {date.today().isoformat()} via "
                "`claudron init --personal`. Captures land as maturity: "
                "draft; promote what proves true."
            ),
            owner=_derive_owner(args),
        )
        smoke_ok = result.action == "created"
        if smoke_ok:
            data = recall(vault, project=None, query="vault bootstrap")
            smoke_ok = any(
                n["title"] == "Vault Bootstrap" for n in data["notes"]
            )
    except Exception as exc:
        print(f"smoke test failed: {exc}", file=sys.stderr)
        return 1
    if not smoke_ok:
        print(
            "smoke test failed: bootstrap note not served by recall",
            file=sys.stderr,
        )
        return 1

    # Commit the scaffold + bootstrap note so machine B's clone gets it —
    # and say so when it fails (unset git identity is the common cause;
    # an unconditional success message would tell the user to push a
    # commit that doesn't exist). No SyncError catch here by design: git
    # presence is proven by rev-parse above and no timeout is passed, so
    # run_git cannot raise on this path.
    seed_msg = "claudron init --personal"
    run_git(root, "add", "-A")
    committed = run_git(root, "commit", "-m", seed_msg).returncode == 0
    if not committed:
        print(
            "warning: seed commit failed (git identity unset?) — run\n"
            f"  git -C {root} -c user.name=YOU -c user.email=YOU@example.com "
            f"commit -m '{seed_msg}'\n"
            "before pushing to a remote",
            file=sys.stderr,
        )

    if args.json:
        _emit_json(
            "init",
            {
                "root": str(root),
                "personal": True,
                "smoke_test": "passed",
                "committed": committed,
            },
        )
        return 0

    print(f"personal vault ready at {root}")
    print("smoke test: recall found the bootstrap note ✓")
    print()
    print("next steps:")
    print(f"  1. install the session hooks:   claudron --vault {root} hooks install --write")
    print(f"  2. add your private remote:     git -C {root} remote add origin <url> && git -C {root} push -u origin main")
    print(f"  3. on your other machine:       git clone <url> && claudron hooks install --write")
    print(f"  4. point sessions at the vault: export CLAUDRON_VAULT={root}")
    return 0


def cmd_status(args) -> int:
    vault = _resolve_vault(args)
    info = status(vault, stale_days=getattr(args, "stale_days", 90))

    if args.json:
        _emit_json("status", info)
        return 0

    print(f"vault: {info['root']}")
    print(f"docs:  {info['total_docs']}  stale: {info['total_stale']}")
    if info["fleets"]:
        print(f"fleets: {', '.join(info['fleets'])}")
    if info["projects"]:
        print(f"projects: {', '.join(info['projects'])}")
    print()
    for tier_name, tier_info in info["tiers"].items():
        if tier_info["docs"] > 0 or args.verbose:
            stale_str = f"  ({tier_info['stale']} stale)" if tier_info["stale"] else ""
            print(f"  {tier_name}: {tier_info['docs']} docs{stale_str}")

    # Index state + vault warnings are diagnostics, not payload → stderr
    if not info["index_present"]:
        print("index: not built (will auto-build on first lookup)", file=sys.stderr)
    elif not info["index_fresh"]:
        print("index: stale (will auto-rebuild on next lookup)", file=sys.stderr)
    for w in info["warnings"]:
        print(f"warning: {w}", file=sys.stderr)
    return 0


def cmd_lookup(args) -> int:
    vault = _resolve_vault(args)
    query = " ".join(args.query)
    results = lookup(
        query,
        vault,
        project=args.project,
        fleet=args.fleet,
        limit=args.limit,
        include_archived=args.include_archived,
        include_expired=args.include_expired,
    )

    if not results:
        if args.json:
            _emit_json("lookup", {"query": query, "results": []})
        else:
            print(f"no results for '{query}'", file=sys.stderr)
        return 0

    if args.json:
        _emit_json(
            "lookup",
            {
                "query": query,
                "results": [
                    {
                        "title": r.doc.title,
                        "score": r.score,
                        "match_type": r.match_type,
                        "tier": r.doc.tier,
                        "path": str(r.doc.source_path.relative_to(vault.root)),
                        "tags": r.doc.tags,
                    }
                    for r in results
                ],
            },
        )
        return 0

    for r in results:
        rel = r.doc.source_path.relative_to(vault.root)
        tags = f"  [{', '.join(r.doc.tags)}]" if r.doc.tags else ""
        print(f"  [{r.score:3d}] {r.doc.title:<40s} {rel}{tags}")
    return 0


