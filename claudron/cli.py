def _derive_owner(args) -> str:
    """--owner → git config user.name → $USER (docs/CLI_CONTRACT.md)."""
    if getattr(args, "owner", None):
        return args.owner
    import subprocess

    try:
        name = subprocess.run(
            ["git", "config", "user.name"], capture_output=True, text=True, timeout=5
        ).stdout.strip()
        if name:
            return name
    except (OSError, subprocess.TimeoutExpired):
        # TimeoutExpired is a SubprocessError, NOT an OSError — without
        # naming it, the timeout guard guards nothing (review minor 6).
        pass
    return os.environ.get("USER", "unknown")


def cmd_new(args) -> int:
    vault = _resolve_vault(args)
    title = args.title

    try:
        base = resolve_target_dir(
            vault, args.type, project=args.project, fleet=args.fleet
        )
    except ScopeError as exc:
        print(str(exc), file=sys.stderr)
        return 2
    base.mkdir(parents=True, exist_ok=True)

    target = base / f"{slugify(title)}.md"
    if target.exists() and not args.force:
        print(
            f"note already exists: {target}\n  pass --force to overwrite",
            file=sys.stderr,
        )
        return 1

    target.write_text(
        compose_note(
            note_type=args.type,
            title=title,
            owner=_derive_owner(args),
            tags=args.tags.split(",") if args.tags else None,
        )
    )

    if args.edit:
        editor = os.environ.get("EDITOR")
        if editor:
            import subprocess

            subprocess.run([editor, str(target)])
        else:
            print("$EDITOR is not set — note written, not opened", file=sys.stderr)

    if args.json:
        _emit_json("new", {"path": str(target)})
    else:
        print(str(target))
    return 0


def cmd_capture(args) -> int:
    vault = _resolve_vault(args)

    if args.update:
        note_path = vault.root / args.update
        if not is_within_root(note_path, vault.root) or not note_path.is_file():
            print(f"no such note in vault: {args.update}", file=sys.stderr)
            return 2
        if not args.body:
            print("--update requires --body", file=sys.stderr)
            return 2
        try:
            result = append_addendum(vault, note_path, args.body)
        except ScopeError as exc:
            print(str(exc), file=sys.stderr)
            return 2
        return _emit_write_result(args, result)

    if args.stdin:
        try:
            finding = json.loads(sys.stdin.read())
        except json.JSONDecodeError as exc:
            print(f"invalid JSON on stdin: {exc}", file=sys.stderr)
            return 2
    else:
        finding = {}
    note_type = finding.get("type") or args.type
    title = finding.get("title") or args.title
    body = finding.get("body") or args.body or ""
    if not note_type or not title:
        print("capture requires --type and --title (or --stdin JSON)", file=sys.stderr)
        return 2
    tags = finding.get("tags") or (
        [t.strip() for t in args.tags.split(",")] if args.tags else None
    )
    owner = finding.get("owner") or _derive_owner(args)

    try:
        result = capture(
            vault,
            note_type=note_type,
            title=title,
            body=body,
            owner=owner,
            tags=tags,
            project=finding.get("project") or args.project,
            fleet=finding.get("fleet") or args.fleet,
            force=args.force,
        )
    except ScopeError as exc:
        print(str(exc), file=sys.stderr)
        return 2

    return _emit_write_result(args, result)


def _emit_write_result(args, result) -> int:
    """One WriteResult renderer for the write commands (capture --update
    shares it): rejected → findings + exit 1, else action/path + exit 0.

    ``written`` is the load-bearing signal: exit 0 and ``ok:true`` mean the
    command *succeeded*, not that a note landed — a ``suggest_*`` dedup route
    succeeds having written nothing. A programmatic caller (a clauDNA skill
    wrapping the CLI) must branch on ``written`` / ``action``, never on the exit
    code, or it silently drops the deduped finding (docs/CLI_CONTRACT.md)."""
    written = result.action in ("created", "updated")
    if result.action == "rejected":
        if args.json:
            _emit_json(
                "capture",
                {"action": result.action, "path": result.path,
                 "reason": result.reason, "written": False},
                result.errors,
            )
        else:
            for f in result.errors:
                print(f"[{f.code}] {f.severity} — {f.message}", file=sys.stderr)
        return 1

    if args.json:
        _emit_json(
            "capture",
            {"action": result.action, "path": result.path,
             "reason": result.reason, "written": written},
        )
    else:
        print(f"{result.action}: {result.path}")
        if result.action.startswith("suggest_"):
            print(result.reason, file=sys.stderr)
            print("note: nothing written — this is a dedup suggestion, not a "
                  "save (re-run with --update or --force)", file=sys.stderr)
    return 0


def cmd_recall(args) -> int:
    vault = _resolve_vault(args)
    # A derived name with no matching project tier still contributes as
    # the shared-tier relevance term — recall() handles both roles.
    project = args.project or derive_project()
    query = " ".join(args.query) if args.query else None
    data = recall(vault, project=project, query=query, limit=args.limit)

    if args.json:
        _emit_json("recall", data)
        return 0

    brief = render_brief(data)
    if brief:
        print(brief)
    else:
        # Abstention: inject nothing rather than something (stderr only).
        print("no context recalled", file=sys.stderr)
    return 0


def cmd_sync(args) -> int:
    vault = _resolve_vault(args)
    if args.pull_only:
        pull, push = True, False
    elif args.push_only:
        pull, push = False, True
    else:
        pull, push = True, True
    try:
        result = sync(vault, pull=pull, push=push, timeout=args.timeout)
    except SyncError as exc:
        print(str(exc), file=sys.stderr)
        return 3  # environment error (CLI contract)

    if args.json:
        _emit_json("sync", result.to_dict())
    else:
        parts = [
            name
            for name, done in (
                ("committed", result.committed),
                ("pulled", result.pulled),
                ("pushed", result.pushed),
            )
            if done
        ]
        print(f"sync: {', '.join(parts) if parts else 'nothing to do'}")
        if result.detail:
            print(result.detail, file=sys.stderr)
        for path in result.quarantined:
            print(f"conflict — quarantined until resolved: {path}", file=sys.stderr)
    return 0 if result.ok else 1


